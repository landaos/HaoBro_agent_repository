# ============================================
# logging_mw.py - 请求日志中间件
# ============================================
#
# ═══════════════════════════════════════════
# 需要在此文件中编写的中间件：
# ═══════════════════════════════════════════
#
# 1. 定义 LoggingMiddleware(BaseHTTPMiddleware)：
#    - 每个请求进来时：
#      1. 获取 request_id（从 Header 或自动生成 UUID）
#      2. 记录请求开始日志（方法、路径、user_id、query params）
#      3. 记录请求体（注意：太大时要截断）
#      4. 记录响应状态码和处理耗时
#      5. 记录错误级别日志（如果状态 >= 400）
#
# 2. 日志格式（使用 logging）：
#    [2026-07-15 10:00:00] POST /api/v1/chat/completions → 200 in 1.23s | user=xxx | req_id=xxx
#
# 3. 在 main.py 中注册（放在限流中间件之前）：
#    app.add_middleware(LoggingMiddleware)
#
# ═══════════════════════════════════════════
# 使用 logging 替代标准 logging，支持：
# - 自动轮转（按大小/时间）
# - 结构化日志（JSON 格式，对接 ELK）
# - 不同环境不同级别（dev→DEBUG, prod→INFO）
# ═══════════════════════════════════════════
