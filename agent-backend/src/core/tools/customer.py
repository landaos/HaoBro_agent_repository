# ============================================
# customer.py - 客户相关工具
# ============================================
#
# ═══════════════════════════════════════════
# 需要在此文件中编写的工具函数：
# ═══════════════════════════════════════════
#
# 1. get_customer_info(customer_id: str) -> str
#    - 功能：按客户 ID 查询客户信息
#    - 输入：customer_id
#    - 输出：客户姓名、等级、联系方式等
#
# 2. get_customer_orders(customer_id: str) -> str
#    - 功能：查询某个客户的所有订单
#    - 输入：customer_id
#    - 输出：订单列表
#
# 3. 将来可以增加的：
#    - get_vip_level(customer_id) → 会员等级
#    - get_customer_history(customer_id) → 历史交互记录
#
# ═══════════════════════════════════════════
# 工具函数应保持纯函数风格：
# - 接收简单参数，返回格式化字符串
# - 内部可调用数据库（通过 service 层）或第三方 API
# - 不要直接操作消息/state，只做具体业务操作
# ═══════════════════════════════════════════
